#!/usr/bin/env bash
set -euo pipefail

# Reproduces the 2026-07-10 four-model comparison packet.
#
# Runs are staged in a directory outside the repo so run manifests capture a
# clean git state (dirty=false) while artifacts are generated, then moved into
# reports/comparison-packet-20260710/.
#
# API keys: source your credentials file before or via the block below.
# ANTHROPIC_API_KEY and OPENAI_API_KEY must be set. Never commit key material.

ROOT="${TMPDIR:-/tmp}/fce-comparison-packet-20260710"
DEST=reports/comparison-packet-20260710

# max_tokens is set to 8192 uniformly across all four models so arms stay
# comparable. It is a cap, not a target. On claude-fable-5 thinking is always
# on and max_tokens covers thinking + text, so a small cap starves the text
# block (thinking-only responses with stop_reason max_tokens).
MAXTOK=8192
TIMEOUT=600

if [ -e "$ROOT" ]; then
  printf "staging root already exists: %s\n" "$ROOT" >&2
  exit 1
fi

set -a
# shellcheck disable=SC1090
source ~/fiduciary-alignment/.env
set +a

mkdir -p "$ROOT"

run_baseline () {
  local provider="$1" model="$2" dir="$3"
  PYTHONPATH=src python3 -m fiduciary.fce run-pilot \
    --output-dir "$ROOT/$dir" \
    --execution fixtures \
    --baseline-adapter live \
    --provider "$provider" \
    --model "$model" \
    --arms raw_model prompted_model rules_available_model \
    --max-output-tokens "$MAXTOK" \
    --timeout-seconds "$TIMEOUT"
}

run_baseline anthropic claude-fable-5   anthropic-claude-fable-5
run_baseline anthropic claude-opus-4-8  anthropic-claude-opus-4-8
run_baseline anthropic claude-sonnet-5  anthropic-claude-sonnet-5
run_baseline openai    gpt-5.5          openai-gpt-5.5

# Runtime arm: no API calls. Runtime execution mode auto-selects the
# runtime-executable scenarios (those with a runtime_case).
PYTHONPATH=src python3 -m fiduciary.fce run-pilot \
  --output-dir "$ROOT/prismweft-runtime" \
  --execution runtime \
  --arms prismweft_runtime

# Curate into the repo (PACKET.md and extract_summary.py are maintained
# in-repo and are not regenerated by this script).
for d in anthropic-claude-fable-5 anthropic-claude-opus-4-8 anthropic-claude-sonnet-5 openai-gpt-5.5 prismweft-runtime; do
  rm -rf "$DEST/$d"
  mv "$ROOT/$d" "$DEST/$d"
done
rmdir "$ROOT"

# Regenerate the PACKET.md source tables from the actual CSVs/manifests:
#   PYTHONPATH=src python3 reports/comparison-packet-20260710/extract_summary.py reports/comparison-packet-20260710
